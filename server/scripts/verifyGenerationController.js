const OWNER = `controller-test:${randomUUID()}`;

const created = {
  courses: [],
  modules: [],
  lessons: [],
};

function deferred() {
  let resolve;
  const promise = new Promise((done) => {
    resolve = done;
  });

  return { promise, resolve };
}

// Makes a broken test fail rather than wait indefinitely.
async function withDeadline(promise) {
  let timer;

  try {
    return await Promise.race([
      promise,
      new Promise((_, reject) => {
        timer = setTimeout(
          () => reject(new Error('Timed out waiting for the generator.')),
          10_000,
        );
      }),
    ]);
  } finally {
    clearTimeout(timer);
  }
}

async function createFixture(creator = OWNER) {
  const courseId = new mongoose.Types.ObjectId();
  const moduleId = new mongoose.Types.ObjectId();
  const lessonId = new mongoose.Types.ObjectId();

  // Record IDs before writing, so partial setup can be cleaned up.
  created.courses.push(courseId);
  created.modules.push(moduleId);
  created.lessons.push(lessonId);

  await Course.create({
    _id: courseId,
    title: 'Controller test course',
    creator,
    modules: [moduleId],
  });

  await Module.create({
    _id: moduleId,
    title: 'Test module',
    course: courseId,
    lessons: [lessonId],
  });

  await Lesson.create({
    _id: lessonId,
    title: 'Test lesson',
    course: courseId,
    module: moduleId,
  });

  return lessonId;
}

async function verify() {
  assert.ok(process.env.TEST_MONGO_URI, 'Set TEST_MONGO_URI first.');

  await mongoose.connect(process.env.TEST_MONGO_URI, {
    dbName: 'learnsmith_generation_test',
    serverSelectionTimeoutMS: 8000,
  });

  const enteredGenerator = deferred();
  const releaseGenerator = deferred();

  let server;
  let generatorCalls = 0;
  const generationContexts = [];
  let quotaCalls = 0;
  let denyQuota = false;
  let courseGeneratorCalls = 0;
  let courseSaveCalls = 0;
  let courseQuotaCalls = 0;
  let shouldBlock = true;
  let failNext = false;

  async function fakeGenerate(args, tracking) {
    assert.equal(args.courseContext.course.title, 'Controller test course');
    assert.equal(args.courseContext.current.title, args.lessonTitle);
    assert.ok(args.courseContext.outline.some((entry) => entry.relation === 'current'));
    assert.ok(!JSON.stringify(args.courseContext).includes('FOREIGN_CONTEXT'));
    assert.equal(tracking.creator, OWNER);
    assert.match(tracking.generationId, /^[0-9a-f-]{36}$/);
    generationContexts.push(tracking);
    generatorCalls += 1;
    if (generatorCalls === 1) {
      assert.equal(args.courseContext.course.description, 'Build controller skills');
      assert.equal(args.courseContext.current.position, 2);
      assert.equal(args.courseContext.outline[0].relation, 'earlier_planned');
      assert.deepEqual(args.courseContext.outline[0].objectives, ['Explain the foundation']);
      assert.ok(!JSON.stringify(args.courseContext).includes('BODY_MUST_NOT_REACH_PROVIDER'));
    }

    if (failNext) {
      failNext = false;
      throw new ApiError(
        502,
        'ai_unavailable',
        'Simulated generator failure.',
      );
    }

    if (shouldBlock) {
      enteredGenerator.resolve();
      await releaseGenerator.promise;
    }

    return {
      lesson: {
        objectives: ['Understand controller testing'],
        content: [
          { type: 'paragraph', text: 'Generated by our test fake.' },
        ],
      },
      ms: 0,
    };
  }

  try {
    const app = express();
    app.use(express.json());

    // Test-only identity. We are testing ownership enforcement,
    // not Auth0 token verification.
    app.use((req, res, next) => {
      req.creator = OWNER;
      req.identityType = 'user';
      next();
    });

    const handler = createGenerateLessonContent({
      generate: fakeGenerate,
      resolveVideos: async (content) => content,
      consumeQuota: async (args) => {
        assert.deepEqual(args, {
          creator: OWNER,
          identityType: 'user',
          resource: 'lessons',
        });
        quotaCalls += 1;
        if (denyQuota) {
          throw new ApiError(429, 'daily_quota_exceeded', 'Simulated quota exhaustion.');
        }
      },
    });

    app.post('/api/lessons/:id/generate', handler);
    app.get('/api/lessons/:id/generation', getLessonGenerationStatus);
    // This route exercises the real quota service with a fake AI generator.
    app.post('/api/quota-lessons/:id/generate', createGenerateLessonContent({
      generate: fakeGenerate,
      resolveVideos: async (content) => content,
    }));
    app.post('/api/courses/generate', createCourseHandler({
      generate: async (topic, tracking) => {
        assert.equal(tracking.creator, OWNER);
        assert.match(tracking.generationId, /^[0-9a-f-]{36}$/);
        courseGeneratorCalls += 1;
        return { ...ready, attempts: 1, ms: 0 };
      },
      reserve: async (args) => {
        courseQuotaCalls += 1;
        assert.equal(args.creator, OWNER);
        assert.equal(args.identityType, 'user');
        assert.match(args.generationId, /^[0-9a-f-]{36}$/);
        return reserveCourseAttempt(args);
      },
      save: async (course, creator) => {
        courseSaveCalls += 1;
        assert.equal(creator, OWNER);
        return course;
      },
    }));
    app.use(errorHandler);

    // Choose an available local port automatically.
    server = app.listen(0, '127.0.0.1');
    await once(server, 'listening');

    const baseUrl = `http://127.0.0.1:${server.address().port}`;

    async function post(lessonId, prefix = '/api/lessons') {
      const response = await fetch(
        `${baseUrl}${prefix}/${lessonId}/generate`,
        {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ courseContext: { course: { title: 'FOREIGN_CONTEXT' } } }),
          signal: AbortSignal.timeout(15_000),
        },
      );

      return {
        status: response.status,
        body: await response.json(),
      };
    }

    // TEST 1: Deliberately overlap two requests.
    const lessonId = await createFixture();

    // Stored metadata, not request-body context or prerequisite bodies, reaches AI.
    const target = await Lesson.findById(lessonId);
    const earlierId = new mongoose.Types.ObjectId();
    created.lessons.push(earlierId);
    await Lesson.create({ _id: earlierId, title: 'Planned foundation',
      course: target.course, module: target.module, objectives: ['Explain the foundation'],
      content: [{ text: 'BODY_MUST_NOT_REACH_PROVIDER' }], isEnriched: false });
    await Module.updateOne({ _id: target.module }, { $set: { lessons: [earlierId, lessonId] } });
    await Course.updateOne({ _id: target.course }, { $set: { description: 'Build controller skills' } });

    const requestA = post(lessonId);
    // Observe early rejection while we wait for the generator signal.
    requestA.catch(() => {});

    await withDeadline(enteredGenerator.promise);
    assert.equal(
      (await Lesson.findById(lessonId)).generationAttemptId,
      generationContexts[0].generationId,
    );

    // A is inside the fake generator and cannot finish yet.
    const responseB = await post(lessonId);

    assert.equal(responseB.status, 409);
    assert.equal(
      responseB.body.error.code,
      'generation_in_progress',
    );
    assert.equal(generatorCalls, 1);
    assert.equal(quotaCalls, 1);

    const activeStatus = await fetch(`${baseUrl}/api/lessons/${lessonId}/generation`);
    const activeBody = await activeStatus.json();
    assert.equal(activeStatus.status, 200);
    assert.equal(activeStatus.headers.get('cache-control'), 'private, no-store');
    assert.equal(activeBody.generation.state, 'generating');
    assert.ok(activeBody.generation.retryAt);
    assert.equal(activeBody.lesson.isEnriched, false);
    assert.equal(generatorCalls, 1);
    assert.equal(quotaCalls, 1);

    releaseGenerator.resolve();

    const responseA = await requestA;
    assert.equal(responseA.status, 200);
    assert.equal(responseA.body.isEnriched, true);

    shouldBlock = false;

    console.log('PASS: Overlapping requests invoke the generator once.');

    // TEST 2: Completed lessons are returned from the database.
    const cached = await post(lessonId);

    assert.equal(cached.status, 200);
    assert.equal(cached.body.content[0].text,
      'Generated by our test fake.');
    assert.equal(generatorCalls, 1);
    assert.equal(quotaCalls, 1);

    console.log('PASS: Cached requests do not invoke the generator.');

    const savedStatus = await (await fetch(`${baseUrl}/api/lessons/${lessonId}/generation`)).json();
    assert.equal(savedStatus.generation.state, 'ready');
    assert.equal(savedStatus.lesson.content[0].text, 'Generated by our test fake.');

    // TEST 3: A different owner's lesson is inaccessible.
    const foreignLessonId = await createFixture('another-test-owner');
    const forbidden = await post(foreignLessonId);

    assert.equal(forbidden.status, 404);
    assert.equal(forbidden.body.error.code, 'lesson_not_found');
    assert.equal(generatorCalls, 1);
    assert.equal(quotaCalls, 1);

    assert.equal((await fetch(`${baseUrl}/api/lessons/${foreignLessonId}/generation`)).status, 404);
    const expiredId = await createFixture();
    await Lesson.updateOne({ _id: expiredId }, { $set: {
      generationStatus: 'generating', generationAttemptId: randomUUID(), generationLeaseExpiresAt: new Date(0),
    } });
    const expiredStatus = await (await fetch(`${baseUrl}/api/lessons/${expiredId}/generation`)).json();
    assert.equal(expiredStatus.generation.state, 'retryable');
    assert.equal(expiredStatus.lesson.isEnriched, false);
    assert.equal(generatorCalls, 1);
    assert.equal(quotaCalls, 1);
    console.log('PASS: Status reads preserve ownership, expose expiry/ready states, and consume no quota or AI calls.');

    console.log('PASS: Ownership is checked before generation.');

    // TEST 4: Failure reaches the client and permits retry.
    const retryLessonId = await createFixture();
    failNext = true;

    const failure = await post(retryLessonId);

    assert.equal(failure.status, 502);
    assert.equal(failure.body.error.code, 'ai_unavailable');
    assert.equal(generatorCalls, 2);

    const failedLesson = await Lesson.findById(retryLessonId);
    assert.equal(failedLesson.generationStatus, 'failed');

    const retry = await post(retryLessonId);

    assert.equal(retry.status, 200);
    assert.equal(retry.body.isEnriched, true);
    assert.equal(generatorCalls, 3);
    assert.equal(quotaCalls, 3);

    console.log('PASS: Failed generation returns 502 and can be retried.');

    // TEST 5: Quota rejection must not call AI or leave the claim occupied.
    const deniedLessonId = await createFixture();
    denyQuota = true;
    const denied = await post(deniedLessonId);
    assert.equal(denied.status, 429);
    assert.equal(denied.body.error.code, 'daily_quota_exceeded');
    assert.equal(generatorCalls, 3);
    assert.equal(quotaCalls, 4);

    const deniedLesson = await Lesson.findById(deniedLessonId);
    assert.equal(deniedLesson.isEnriched, false);
    assert.equal(deniedLesson.generationStatus, 'failed');
    assert.equal(deniedLesson.generationAttemptId, null);
    assert.equal(deniedLesson.generationLeaseExpiresAt, null);

    denyQuota = false;
    const allowedRetry = await post(deniedLessonId);
    assert.equal(allowedRetry.status, 200);
    assert.equal(generatorCalls, 4);
    assert.equal(quotaCalls, 5);
    console.log('PASS: Quota denial skips AI, releases the claim, and permits a later retry.');

    // TEST 6: Verify actual daily exhaustion through the HTTP controller.
    await DailyUsage.init();
    const day = new Date().toISOString().slice(0, 10);
    await DailyUsage.create({ creator: OWNER, day, lessons: 20, courses: 0 });
    const exhaustedLessonId = await createFixture();
    const exhausted = await post(exhaustedLessonId, '/api/quota-lessons');
    assert.equal(exhausted.status, 429);
    assert.equal(exhausted.body.error.code, 'daily_quota_exceeded');
    assert.equal(generatorCalls, 4);
    const exhaustedLesson = await Lesson.findById(exhaustedLessonId);
    assert.equal(exhaustedLesson.generationStatus, 'failed');
    assert.equal(exhaustedLesson.generationAttemptId, null);

    const cachedAtLimit = await post(lessonId, '/api/quota-lessons');
    assert.equal(cachedAtLimit.status, 200);
    assert.equal(generatorCalls, 4);
    assert.equal((await DailyUsage.findOne({ creator: OWNER, day })).lessons, 20);
    console.log('PASS: Real quota exhaustion blocks generation while cached lessons remain readable.');

    async function postCourse(prompt) {
      const response = await fetch(`${baseUrl}/api/courses/generate`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ prompt }),
        signal: AbortSignal.timeout(15_000),
      });
      return { status: response.status, body: await response.json() };
    }

    // TEST 7: Input validation precedes quota; real course quota precedes AI.
    const invalidCourse = await postCourse('   ');
    assert.equal(invalidCourse.status, 400);
    assert.equal(courseQuotaCalls, 0);
    assert.equal(courseGeneratorCalls, 0);
    assert.equal(courseSaveCalls, 0);

    const courseResponses = await Promise.all(
      Array.from({ length: 4 }, () => postCourse('Concurrency')),
    );
    assert.equal(courseResponses.filter((response) => response.status === 201).length, 3);
    const courseRejections = courseResponses.filter((response) => response.status !== 201);
    assert.equal(courseRejections.length, 1);
    assert.equal(courseRejections[0].status, 429);
    assert.equal(courseRejections[0].body.error.code, 'daily_quota_exceeded');
    assert.equal(courseQuotaCalls, 4);
    assert.equal(courseGeneratorCalls, 3);
    assert.equal(courseSaveCalls, 3);
    const finalUsage = await DailyUsage.findOne({ creator: OWNER, day });
    assert.equal(finalUsage.courses, 3);
    assert.equal(finalUsage.lessons, 20);
    console.log('PASS: Invalid course input uses no quota; four concurrent course requests admit only three.');

    const brokenId = await createFixture();
    const broken = await Lesson.findById(brokenId);
    await Module.updateOne({ _id: broken.module }, { $set: { lessons: [] } });
    const beforeBroken = { generatorCalls, quotaCalls };
    const brokenResponse = await post(brokenId);
    assert.equal(brokenResponse.status, 409);
    assert.equal(brokenResponse.body.error.code, 'lesson_outline_invalid');
    assert.deepEqual({ generatorCalls, quotaCalls }, beforeBroken);
    assert.equal((await Lesson.findById(brokenId)).generationAttemptId, null);
    console.log('PASS: Invalid outline fails before quota/provider work and releases the claim.');

    const isolatedId = await createFixture();
    const isolated = await Lesson.findById(isolatedId);
    const foreign = await Lesson.findById(foreignLessonId);
    await Course.updateOne({ _id: isolated.course }, { $push: { modules: foreign.module } });
    await Module.updateOne({ _id: isolated.module }, { $push: { lessons: foreignLessonId } });
    await Course.updateOne({ _id: foreign.course }, { $set: { title: 'FOREIGN_CONTEXT' } });
    await Module.updateOne({ _id: foreign.module }, { $set: { title: 'FOREIGN_CONTEXT' } });
    await Lesson.updateOne({ _id: foreignLessonId }, { $set: { title: 'FOREIGN_CONTEXT' } });
    assert.equal((await post(isolatedId)).status, 200);
    console.log('PASS: Context queries exclude foreign course references in stored arrays.');
  } finally {
    // Release blocked work even if an assertion failed.
    releaseGenerator.resolve();

    if (server) {
      await new Promise((resolve, reject) => {
        server.close((err) => (err ? reject(err) : resolve()));
      });
    }

    try {
      await Lesson.deleteMany({ _id: { $in: created.lessons } });
      await Module.deleteMany({ _id: { $in: created.modules } });
      await Course.deleteMany({ _id: { $in: created.courses } });
      await DailyUsage.deleteMany({ creator: OWNER });
    } finally {
      await mongoose.disconnect();
    }
  }
}

verify().catch((err) => {
  console.error('FAIL:', err);
  process.exitCode = 1;
});
