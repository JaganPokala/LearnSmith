import assert from 'node:assert/strict';
import { once } from 'node:events';
import express from 'express';
import mongoose from 'mongoose';
import dotenv from 'dotenv';

import Course from '../models/Course.js';
import Module from '../models/Module.js';
import Lesson from '../models/Lesson.js';

import {
  createGenerateLessonContent,
} from '../controllers/lessonController.js';

import {
  ApiError,
  errorHandler,
} from '../middlewares/errorHandler.js';

dotenv.config({
  path: new URL('../../.env', import.meta.url),
  quiet: true,
});

const OWNER = 'controller-test-owner';

const created = {
  courses: [],
  modules: [],
  lessons: [],
};

function deferred() {
  let resolve;
  const promise = new Promise((done) => {
    resolve = done;
  });

  return { promise, resolve };
}

// Makes a broken test fail rather than wait indefinitely.
async function withDeadline(promise) {
  let timer;

  try {
    return await Promise.race([
      promise,
      new Promise((_, reject) => {
        timer = setTimeout(
          () => reject(new Error('Timed out waiting for the generator.')),
          10_000,
        );
      }),
    ]);
  } finally {
    clearTimeout(timer);
  }
}

async function createFixture(creator = OWNER) {
  const courseId = new mongoose.Types.ObjectId();
  const moduleId = new mongoose.Types.ObjectId();
  const lessonId = new mongoose.Types.ObjectId();

  // Record IDs before writing, so partial setup can be cleaned up.
  created.courses.push(courseId);
  created.modules.push(moduleId);
  created.lessons.push(lessonId);

  await Course.create({
    _id: courseId,
    title: 'Controller test course',
    creator,
    modules: [moduleId],
  });

  await Module.create({
    _id: moduleId,
    title: 'Test module',
    course: courseId,
    lessons: [lessonId],
  });

  await Lesson.create({
    _id: lessonId,
    title: 'Test lesson',
    course: courseId,
    module: moduleId,
  });

  return lessonId;
}

async function verify() {
  assert.ok(process.env.TEST_MONGO_URI, 'Set TEST_MONGO_URI first.');

  await mongoose.connect(process.env.TEST_MONGO_URI, {
    dbName: 'learnsmith_generation_test',
    serverSelectionTimeoutMS: 8000,
  });

  const enteredGenerator = deferred();
  const releaseGenerator = deferred();

  let server;
  let generatorCalls = 0;
  let shouldBlock = true;
  let failNext = false;

  async function fakeGenerate() {
    generatorCalls += 1;

    if (failNext) {
      failNext = false;
      throw new ApiError(
        502,
        'ai_unavailable',
        'Simulated generator failure.',
      );
    }

    if (shouldBlock) {
      enteredGenerator.resolve();
      await releaseGenerator.promise;
    }

    return {
      lesson: {
        objectives: ['Understand controller testing'],
        content: [
          { type: 'paragraph', text: 'Generated by our test fake.' },
        ],
      },
      ms: 0,
    };
  }

  try {
    const app = express();
    app.use(express.json());

    // Test-only identity. We are testing ownership enforcement,
    // not Auth0 token verification.
    app.use((req, res, next) => {
      req.creator = OWNER;
      next();
    });

    const handler = createGenerateLessonContent({
      generate: fakeGenerate,
      resolveVideos: async (content) => content,
    });

    app.post('/api/lessons/:id/generate', handler);
    app.use(errorHandler);

    // Choose an available local port automatically.
    server = app.listen(0, '127.0.0.1');
    await once(server, 'listening');

    const baseUrl = `http://127.0.0.1:${server.address().port}`;

    async function post(lessonId) {
      const response = await fetch(
        `${baseUrl}/api/lessons/${lessonId}/generate`,
        {
          method: 'POST',
          signal: AbortSignal.timeout(15_000),
        },
      );

      return {
        status: response.status,
        body: await response.json(),
      };
    }

    // TEST 1: Deliberately overlap two requests.
    const lessonId = await createFixture();

    const requestA = post(lessonId);
    // Observe early rejection while we wait for the generator signal.
    requestA.catch(() => {});

    await withDeadline(enteredGenerator.promise);

    // A is inside the fake generator and cannot finish yet.
    const responseB = await post(lessonId);

    assert.equal(responseB.status, 409);
    assert.equal(
      responseB.body.error.code,
      'generation_in_progress',
    );
    assert.equal(generatorCalls, 1);

    releaseGenerator.resolve();

    const responseA = await requestA;
    assert.equal(responseA.status, 200);
    assert.equal(responseA.body.isEnriched, true);

    shouldBlock = false;

    console.log('PASS: Overlapping requests invoke the generator once.');

    // TEST 2: Completed lessons are returned from the database.
    const cached = await post(lessonId);

    assert.equal(cached.status, 200);
    assert.equal(cached.body.content[0].text,
      'Generated by our test fake.');
    assert.equal(generatorCalls, 1);

    console.log('PASS: Cached requests do not invoke the generator.');

    // TEST 3: A different owner's lesson is inaccessible.
    const foreignLessonId = await createFixture('another-test-owner');
    const forbidden = await post(foreignLessonId);

    assert.equal(forbidden.status, 404);
    assert.equal(forbidden.body.error.code, 'lesson_not_found');
    assert.equal(generatorCalls, 1);

    console.log('PASS: Ownership is checked before generation.');

    // TEST 4: Failure reaches the client and permits retry.
    const retryLessonId = await createFixture();
    failNext = true;

    const failure = await post(retryLessonId);

    assert.equal(failure.status, 502);
    assert.equal(failure.body.error.code, 'ai_unavailable');
    assert.equal(generatorCalls, 2);

    const failedLesson = await Lesson.findById(retryLessonId);
    assert.equal(failedLesson.generationStatus, 'failed');

    const retry = await post(retryLessonId);

    assert.equal(retry.status, 200);
    assert.equal(retry.body.isEnriched, true);
    assert.equal(generatorCalls, 3);

    console.log('PASS: Failed generation returns 502 and can be retried.');
  } finally {
    // Release blocked work even if an assertion failed.
    releaseGenerator.resolve();

    if (server) {
      await new Promise((resolve, reject) => {
        server.close((err) => (err ? reject(err) : resolve()));
      });
    }

    try {
      await Lesson.deleteMany({ _id: { $in: created.lessons } });
      await Module.deleteMany({ _id: { $in: created.modules } });
      await Course.deleteMany({ _id: { $in: created.courses } });
    } finally {
      await mongoose.disconnect();
    }
  }
}

verify().catch((err) => {
  console.error('FAIL:', err);
  process.exitCode = 1;
});